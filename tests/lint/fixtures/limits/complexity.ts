export function classify(n: number): string {
  if (n === 1) return 'w1'
  if (n === 2) return 'w2'
  if (n === 3) return 'w3'
  if (n === 4) return 'w4'
  if (n === 5) return 'w5'
  if (n === 6) return 'w6'
  if (n === 7) return 'w7'
  if (n === 8) return 'w8'
  if (n === 9) return 'w9'
  if (n === 10) return 'w10'
  if (n === 11) return 'w11'
  return 'rest'
}
